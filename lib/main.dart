class _MainDashboardState extends State<MainDashboard> {
  bool _setupDialogShown = false; // Prompt at most once per app session

  /// Wraps the main content area so it can be captured to an image for the
  /// screenshot annotator.
  final GlobalKey _captureKey = GlobalKey();

  /// Captures the current content area and opens the annotation editor. The
  /// default file name embeds the active tab + date.
  void _takeScreenshot(BuildContext context, int selectedIndex) {
    final tabToken =
        (selectedIndex >= 0 && selectedIndex < AppTab.values.length)
            ? AppTab.values[selectedIndex].token
            : 'view';
    final dateToken = DateTime.now().toLocal().toIso8601String().split('T').first;
    captureAndAnnotate(context, _captureKey,
        defaultFileName: '${tabToken}_screenshot_$dateToken.png');
  }

  /// Creates a new config from the template. Shared by the toolbar button
  /// (always available) and the landing screen button: asks for confirmation
  /// first when a config is already loaded, and routes to App Config with an
  /// explanation when no template can be found.
  Future<void> _createNewConfig(
      BuildContext context, AppStateProvider provider) async {
    if (provider.roomConfig.isNotEmpty) {
      final bool? confirmed = await showDialog<bool>(
        context: context,
        builder: (ctx) => AlertDialog(
          title: const Text('Create New Config?'),
          content: const Text(
              'This replaces the currently loaded configuration with a fresh '
              'one from the template. Unsaved changes will be lost.'),
          actions: [
            TextButton(
              onPressed: () => Navigator.of(ctx).pop(false),
              child: const Text('Cancel'),
            ),
            ElevatedButton(
              onPressed: () => Navigator.of(ctx).pop(true),
              child: const Text('Create New'),
            ),
          ],
        ),
      );
      if (confirmed != true) return;
    }
    if (!context.mounted) return;

    // Two questions that change what the rest of the session looks like: is
    // there a control system yet, and are the devices coming from the cost
    // estimator? Both default to the old behavior.
    final NewRoomChoice? choice = await showNewRoomDialog(context);
    if (choice == null || !context.mounted) return;

    // The template path always resolves (explicit file, else config.json in
    // the Root Folder / working directory), so just attempt the create and
    // report the resolved location on failure.
    final bool success = await provider.createNewConfig();
    if (!context.mounted) return;
    if (success) {
      // Set after the create: createNewConfig resets the AV document, and the
      // room mode lives in it.
      provider.setRoomMode(choice.mode);

      // The room type goes in before the estimator wizard, so anything picked
      // there lands on a canvas that already has the room's usual gear on it
      // rather than colliding with it afterwards.
      final preset = choice.preset;
      if (preset != null) {
        final summary = provider.applyRoomPreset(
          preset,
          // Renumbered into this room's own scheme when it has a number. A new
          // room usually doesn't yet, and then the preset's numbering stands
          // until somebody renumbers the boxes.
          jackPrefix: _roomJackPrefix(provider),
        );

        // The control side, built from what the preset just drew. Skipped for
        // an AV-only room, which by definition has no control system yet — the
        // banner on the Wizard tab is how that room gets one, when somebody
        // decides it should have one.
        final control = choice.mode == RoomMode.avOnly
            ? null
            : buildControlSideForPreset(provider, preset);

        if (!context.mounted) return;
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            duration: const Duration(seconds: 8),
            content: Text(
              '${preset.name}: ${summary.devices} devices, ${summary.jacks} '
              'jacks, ${summary.cables} runs and ${summary.racks} rack'
              '${summary.racks == 1 ? '' : 's'} added.'
              '${control == null ? '' : ' ${control.blocks} control block'
                  '${control.blocks == 1 ? '' : 's'} and ${control.settings} '
                  'system setting${control.settings == 1 ? '' : 's'} filled in'
                  '${control.withoutModule == 0 ? '' : ', ${control.withoutModule} '
                      'device${control.withoutModule == 1 ? '' : 's'} still '
                      'needing a python module'}.'}'
              ' Set the room number on the Wizard tab, then check the jack '
              'numbering.',
            ),
          ),
        );
      }

      if (choice.startFromEstimator) {
        final placed = await showDeviceStartWizard(context, provider);
        if (!context.mounted) return;
        if (placed > 0) {
          // Straight to the estimate: the list was just priced, and the
          // numbers are what the wizard was opened for.
          provider.selectTab(AppTab.cost.index);
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(
              content: Text(
                '$placed device${placed == 1 ? '' : 's'} added — they are on '
                'the Signal Flow canvas and priced here.',
              ),
            ),
          );
          return;
        }
      }

      // An AV-only room starts on the Wizard tab, which is where its two
      // required answers (building and room number) live.
      if (choice.mode == RoomMode.avOnly) {
        provider.selectTab(AppTab.wizard.index);
      }
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(
            choice.mode == RoomMode.avOnly
                ? 'New AV-only room created. Set the building and room '
                      'number, then add the devices.'
                : 'New config created from template.',
          ),
        ),
      );
    } else {
      provider.selectTab(AppTab.appConfig.index);
      ScaffoldMessenger.of(context).showSnackBar(SnackBar(
          content: Text("No template found at ${provider.effectiveTemplateFilePath}. "
              "Place config.json there or set a Template file in App Config."),
          backgroundColor: Colors.red));
    }
  }

  /// This room's jack prefix — its number, digits only. '' when the room has
  /// no number yet, which tells [AppStateProvider.applyRoomPreset] to leave a
  /// preset's own numbering alone rather than renumbering it to nothing.
  static String _roomJackPrefix(AppStateProvider provider) {
    final setup = provider.roomConfig['SYSTEM_SETUP'];
    final room = (setup is Map ? setup['gve_room']?.toString() : null) ?? '';
    return room.replaceAll(RegExp(r'[^0-9]'), '');
  }

  /// Puts the working file back the way it was before the last save, after
  /// showing exactly what that costs.
  ///
  /// The dialog lists the differences between the backup and the config on
  /// screen — which is more than the save wrote, because any editing done
  /// since is in there too and goes with it. That list is the whole point of
  /// the confirmation: "undo a save" is easy to press expecting only the last
  /// thing you typed to come back.
  Future<void> _undoLastSave(
      BuildContext context, AppStateProvider provider) async {
    final List<ConfigDelta> deltas = await provider.undoDeltas();
    if (!context.mounted) return;

    if (deltas.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(const SnackBar(
        content: Text('Nothing to undo — the config already matches the backup.'),
      ));
      return;
    }

    final String backupName =
        provider.saveBackupPath.split(Platform.pathSeparator).last;
    final bool? confirmed = await showDialog<bool>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: Row(children: [
          const Icon(Icons.undo, color: Colors.orange),
          const SizedBox(width: 10),
          Expanded(
              child: Text('Undo Last Save',
                  style: Theme.of(ctx).textTheme.titleLarge)),
        ]),
        content: SizedBox(
          width: 560,
          height: 340,
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Text('Restoring $backupName rewrites both the file and what is '
                  'on screen. ${deltas.length} propert'
                  '${deltas.length == 1 ? 'y' : 'ies'} would change — this '
                  'includes anything you have edited since that save:'),
              const SizedBox(height: 12),
              Expanded(
                child: Container(
                  padding: const EdgeInsets.all(12),
                  decoration: BoxDecoration(
                    borderRadius: BorderRadius.circular(4),
                    border: Border.all(color: Theme.of(ctx).dividerColor),
                  ),
                  child: ListView.builder(
                    itemCount: deltas.length,
                    itemBuilder: (context, index) => Padding(
                      padding: const EdgeInsets.only(bottom: 6.0),
                      child: Text(deltas[index].summary,
                          style: const TextStyle(
                              fontFamily: 'monospace', fontSize: 12)),
                    ),
                  ),
                ),
              ),
            ],
          ),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.of(ctx).pop(false),
            child: const Text('Cancel'),
          ),
          ElevatedButton.icon(
            icon: const Icon(Icons.undo, size: 18),
            label: const Text('Restore Backup'),
            onPressed: () => Navigator.of(ctx).pop(true),
          ),
        ],
      ),
    );
    if (confirmed != true || !context.mounted) return;

    final bool ok = await provider.undoLastSave();
    if (!context.mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(SnackBar(
      content: Text(ok
          ? 'Restored $backupName — the file and the editor are back to the '
              'previous save.'
          : 'Could not restore $backupName; nothing was changed.'),
      backgroundColor: ok ? Colors.green : Colors.orange.shade800,
    ));
  }

  /// Brings the schematic in line with the config that was just opened.
  ///
  /// A saved `<config>_control_schematic.json` belongs to the config file, so
  /// loaded from that folder as soon as the config is — no need to visit the
  /// Schematic tab first. The one case that isn't obvious is a session that has
  /// already arranged a diagram of its own: then the user is asked whether to
  /// take the saved one or discard it and keep what's on screen.
  Future<void> _syncSchematicAfterLoad(
      BuildContext context, AppStateProvider provider) async {
    if (!provider.schematicLayoutNeedsChoice) {
      provider.loadSchematicLayoutForCurrentConfig();
      return;
    }
    final bool? loadSaved = await showDialog<bool>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: const Text('Saved control schematic found'),
        content: Text(
            'This config has a saved control schematic beside it:\n\n'
            '${provider.schematicSidecarPath}\n\n'
            'You also have a control schematic arranged in this session. '
            'Load the saved one, or discard it and keep yours?'),
        actions: [
          TextButton(
            onPressed: () => Navigator.of(ctx).pop(false),
            child: const Text('Discard saved, keep mine'),
          ),
          ElevatedButton(
            onPressed: () => Navigator.of(ctx).pop(true),
            child: const Text('Load saved control schematic'),
          ),
        ],
      ),
    );
    // Dismissed without answering: the file's own layout is the safe default.
    if (loadSaved == false) {
      provider.keepSchematicLayoutForCurrentConfig();
    } else {
      provider.loadSchematicLayoutForCurrentConfig();
    }
  }

  /// The AV Flow equivalent of [_syncSchematicAfterLoad], for the
  /// `<config>_av_flow.json` sidecar. Same rule: load it silently unless the
  /// session already has a diagram of its own worth protecting.
  Future<void> _syncAvFlowAfterLoad(
      BuildContext context, AppStateProvider provider) async {
    if (!provider.avFlowNeedsChoice) {
      provider.loadAvFlowForCurrentConfig();
      return;
    }
    final bool? loadSaved = await showDialog<bool>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: const Text('Saved AV flow found'),
        content: Text('This config has a saved AV signal flow beside it:\n\n'
            '${provider.avFlowSidecarPath}\n\n'
            'You also have an AV flow drawn in this session. Load the saved '
            'one, or discard it and keep yours?'),
        actions: [
          TextButton(
            onPressed: () => Navigator.of(ctx).pop(false),
            child: const Text('Discard saved, keep mine'),
          ),
          ElevatedButton(
            onPressed: () => Navigator.of(ctx).pop(true),
            child: const Text('Load saved AV flow'),
          ),
        ],
      ),
    );
    if (loadSaved == false) {
      provider.keepAvFlowForCurrentConfig();
    } else {
      provider.loadAvFlowForCurrentConfig();
    }
  }

  /// Both diagrams belong to the config file, so both sidecars are picked up
  /// together whenever a config is opened or downloaded.
  Future<void> _syncDiagramsAfterLoad(
      BuildContext context, AppStateProvider provider) async {
    await _syncSchematicAfterLoad(context, provider);
    if (!context.mounted) return;
    await _syncAvFlowAfterLoad(context, provider);
  }

  @override
  Widget build(BuildContext context) {
    final provider = context.watch<AppStateProvider>();
    final hasConfig = provider.roomConfig.isNotEmpty;
    // Selected tab lives in the provider so it survives the remount that a
    // theme-family change (Auris <-> Classic) forces via the MaterialApp key.
    final int selectedIndex = provider.selectedTabIndex;

    // FIRST-RUN CHECK: once the saved settings have been read, show the
    // one-time setup dialog asking where each file is located. When setup
    // was completed on an earlier launch this is bypassed entirely.
    if (provider.settingsLoaded &&
        provider.firstRunSetupNeeded &&
        !_setupDialogShown) {
      _setupDialogShown = true;
      WidgetsBinding.instance.addPostFrameCallback((_) {
        if (!mounted) return;
        showDialog(
          context: context,
          barrierDismissible: false,
          builder: (_) => const FirstRunSetupDialog(),
        );
      });
    }

    return Scaffold(
      appBar: AppBar(
        // The app's name, and — once a project is open — which of its rooms
        // you are looking at. Beside the title rather than out in the actions
        // because it is not an action: it says what is on screen.
        title: Row(
          mainAxisSize: MainAxisSize.min,
          children: const [
            // Both halves flexible: at 150% text the app's own name is wider
            // than the title slot on a laptop, so a rigid Text painted an
            // overflow stripe across the top bar before the picker even got a
            // say. The name gives way first — it is the one thing on screen
            // nobody needs to read twice.
            Flexible(
              child: Text('Room Config Builder', overflow: TextOverflow.ellipsis),
            ),
            Flexible(child: ProjectRoomPicker()),
          ],
        ),
        titleSpacing: 16,
        actions: [
          // THE WHOLE JOB IN ONE BOOK, from wherever you are standing. It used
          // to live on two of the twelve tabs, which made "send me the
          // workbook" a question about which page somebody happened to be on.
          IconButton(
            key: const ValueKey('export_workbook'),
            icon: const Icon(Icons.menu_book),
            tooltip: hasConfig
                ? 'Export the full room workbook — every tab, one .xlsx'
                : 'Export the full room workbook — nothing loaded yet',
            onPressed:
                hasConfig ? () => exportRoomWorkbook(context, provider) : null,
          ),
          // ...and THIS tab on its own, the three ways a document leaves this
          // app. Beside the workbook button so the answer to "can I get this
          // as a spreadsheet" is in the same place on every page.
          PopupMenuButton<String>(
            key: const ValueKey('export_tab_menu'),
            icon: const Icon(Icons.file_download_outlined),
            tooltip: _tabExportTooltip(selectedIndex, hasConfig),
            // The catalog is the app's own price list, so it exports with no
            // room loaded — everything else needs one.
            enabled: _tabExports(selectedIndex) &&
                (hasConfig || _tabWorksWithoutConfig(selectedIndex)),
            onSelected: (v) => exportTabReport(
              context,
              provider,
              AppTab.values[selectedIndex],
              v,
            ),
            itemBuilder: (ctx) => [
              PopupMenuItem(
                value: 'xlsx',
                child: Text(
                  '${_tabExportLabel(selectedIndex)} as a spreadsheet (.xlsx)',
                ),
              ),
              PopupMenuItem(
                value: 'txt',
                child: Text(
                  '${_tabExportLabel(selectedIndex)} as plain text (.txt)',
                ),
              ),
              PopupMenuItem(
                value: 'copy',
                child: Text(
                  'Copy ${_tabExportLabel(selectedIndex).toLowerCase()} to the '
                  'clipboard',
                ),
              ),
            ],
          ),
          IconButton(
            icon: const Icon(Icons.photo_camera),
            tooltip: 'Screenshot & annotate',
            onPressed: () => _takeScreenshot(context, selectedIndex),
          ),
          IconButton(
            icon: Icon(provider.isDarkMode ? Icons.light_mode : Icons.dark_mode),
            tooltip: 'Toggle Theme',
            onPressed: () => provider.toggleTheme(),
          ),
          IconButton(
            icon: const Icon(Icons.note_add),
            tooltip: 'New Config (from template)',
            onPressed: () => _createNewConfig(context, provider),
          ),
          // CONVERT: the migration a legacy file needs, on demand. The load
          // already ran the conversion in memory — this is where it gets
          // reviewed, accepted or thrown away. Grayed out when the loaded
          // file had nothing to migrate, so its state is also the answer to
          // "does this room need converting?".
          IconButton(
            icon: Badge(
              // The count is "there is something here to deal with", not "this
              // file was once converted". Once the log has been acknowledged
              // or the preview applied it comes down, and the next load of a
              // file that needs converting puts it back.
              isLabelVisible: provider.conversionNeedsAttention,
              label: Text('${provider.conversionChanges.length}'),
              child: const Icon(Icons.compare_arrows),
            ),
            // The button itself stays live for the whole session: the log is
            // worth being able to reread, and greying it out the moment it was
            // acknowledged would take that away to hide a number.
            tooltip: switch ((
              provider.lastLoadHadChanges,
              provider.conversionAcknowledged,
